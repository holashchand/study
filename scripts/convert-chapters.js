#!/usr/bin/env node
/**
 * Converts java-fundamentals HTML chapters to JSX data files.
 * Run once: node scripts/convert-chapters.js
 */
import { readFileSync, writeFileSync, mkdirSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, '..')
const SRC = join(ROOT, 'java-fundamentals')
const DEST = join(ROOT, 'src/data/courses/java-fundamentals/chapters')

mkdirSync(DEST, { recursive: true })

const chapters = [
  { num: 1, file: 'chapter01-java-foundations.html' },
  { num: 2, file: 'chapter02-data-types-operators.html' },
  { num: 3, file: 'chapter03-control-flow.html' },
  { num: 4, file: 'chapter04-methods-arrays.html' },
  { num: 5, file: 'chapter05-oop.html' },
  { num: 6, file: 'chapter06-collections-apis.html' },
  { num: 7, file: 'chapter07-exceptions-io.html' },
  { num: 8, file: 'chapter08-functional-streams.html' },
  { num: 9, file: 'chapter09-concurrency.html' },
  { num: 10, file: 'chapter10-modern-java.html' },
]

function extractText(html, tag) {
  const m = html.match(new RegExp(`<${tag}[^>]*>([\\s\\S]*?)<\\/${tag}>`, 'i'))
  return m ? m[1].replace(/<[^>]+>/g, '').trim() : ''
}

function cleanHtml(html) {
  // Strip script tags and prism-related content
  html = html.replace(/<script[\s\S]*?<\/script>/gi, '')
  // Remove sidebar injected nav
  html = html.replace(/<nav class="toc"[\s\S]*?<\/nav>/gi, '')
  return html
}

function extractSections(html) {
  const sections = []
  // Match both <section id="..."> and <section class="section" id="...">
  const sectionRegex = /<section[^>]*\bid="([^"]+)"[^>]*>([\s\S]*?)<\/section>/gi
  let m
  while ((m = sectionRegex.exec(html)) !== null) {
    const id = m[1]
    const content = m[2]
    const titleMatch = content.match(/<h2[^>]*>([\s\S]*?)<\/h2>/i)
    const rawTitle = titleMatch ? titleMatch[1].replace(/<[^>]+>/g, '').trim() : id
    sections.push({ id, title: rawTitle, content: content.trim() })
  }
  return sections
}

function escapeForTemplateLiteral(str) {
  return str.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')
}

for (const ch of chapters) {
  const filePath = join(SRC, ch.file)
  let html
  try {
    html = readFileSync(filePath, 'utf8')
  } catch {
    console.warn(`Skipping ${ch.file} — not found`)
    continue
  }

  html = cleanHtml(html)

  // Extract chapter meta from chapter-header
  const titleMatch = html.match(/<h1[^>]*class="chapter-title"[^>]*>([\s\S]*?)<\/h1>/i)
  const subtitleMatch = html.match(/<p[^>]*class="chapter-subtitle"[^>]*>([\s\S]*?)<\/p>/i)
  const title = titleMatch ? titleMatch[1].replace(/<[^>]+>/g, '').trim() : `Chapter ${ch.num}`
  const subtitle = subtitleMatch ? subtitleMatch[1].replace(/<[^>]+>/g, '').trim() : ''

  const sections = extractSections(html)

  if (sections.length === 0) {
    console.warn(`No sections found in ${ch.file}`)
    continue
  }

  const sectionsCode = sections.map(sec => {
    const escapedContent = escapeForTemplateLiteral(sec.content)
    const escapedTitle = sec.title.replace(/'/g, "\\'")
    return `  {
    id: '${sec.id}',
    title: '${escapedTitle}',
    content: () => (
      <div dangerouslySetInnerHTML={{ __html: \`${escapedContent}\` }} />
    ),
  }`
  }).join(',\n')

  const jsx = `// AUTO-GENERATED by scripts/convert-chapters.js — do not edit manually
export const sections = [
${sectionsCode}
]
`

  const outFile = join(DEST, `chapter${String(ch.num).padStart(2, '0')}.jsx`)
  writeFileSync(outFile, jsx, 'utf8')
  console.log(`✓ chapter${String(ch.num).padStart(2, '0')}.jsx — ${sections.length} sections`)
}

console.log('\nDone. Now write src/data/courses/java-fundamentals/meta.js')
